"""The interfaces reading a workspace over SSH

The SSH state provider is connected through a fake ``ssh`` executable put first
on the ``PATH``: it drops the options and the host and runs the remote command
locally (the ``monitor-server`` command, and rsync's remote side when files are
synchronized). Everything else is the real code path: the JSON-RPC server reads
a workspace generated by running a small experiment.
"""

