async def test_service_log_read_locally(ssh_provider, monkeypatch):
    """The logs of a service are read where the live service writes them,
    without asking rsync for them (which created a directory named after the
    log file when it did not exist yet)"""
    synced = []
    monkeypatch.setattr(
        ssh_provider, "sync_path", lambda path, **kwargs: synced.append(path)
    )
    live = find_service(ssh_provider, "greetings", "viewer").to_service()
    url = "/api/services/greetings/viewer/logs/stdout"
    async with DRIVERS["web"](ssh_provider) as ui:
        # No log yet
        response = ui.client.get(url)
        assert response.json()["content"] == ""
        assert not live.stdout.exists()

        live.stdout.parent.mkdir(parents=True, exist_ok=True)
        live.stdout.write_text("serving\n")
        assert ui.client.get(url).json()["content"] == "serving\n"
    assert synced == []


def test_sync_refuses_file(tmp_path, monkeypatch):
    """Synchronizing a path that is a file locally is refused (rsync works on
    directories)"""
    sync = RemoteFileSynchronizer("host", Path("/remote"), tmp_path)
    monkeypatch.setattr(sync, "_rsync", lambda *args, **kwargs: None)
    (tmp_path / "logs.out").write_text("")
    with pytest.raises(ValueError, match="is a file"):
        sync.sync_path("/remote/logs.out")
    assert sync.sync_path("/remote/dir") == tmp_path / "dir"


#: rsync taking a long time (a large first synchronization)
SLOW_RSYNC = """#!/bin/sh
exec sleep 60
"""


def test_service_starts_while_syncing(ssh_provider, tmp_path, monkeypatch):
    """A service starts without waiting for the first synchronization of its
    files, and stopping it kills the running synchronization"""
    bin_dir = tmp_path / "slow-bin"
    bin_dir.mkdir()
    (bin_dir / "rsync").write_text(SLOW_RSYNC)
    (bin_dir / "rsync").chmod(0o755)
    monkeypatch.setenv("PATH", str(bin_dir), prepend=os.pathsep)

    live = find_service(ssh_provider, "greetings", "viewer").to_service()
    start = time.time()
    assert live.get_url() == "http://localhost:1/viewer"
    assert time.time() - start < 10
    assert live.state.name == "RUNNING"

    # The first synchronization is running
    synchronizer = ssh_provider._synchronizer
    deadline = time.time() + 10
    while not synchronizer._processes and time.time() < deadline:
        time.sleep(0.05)
    (process,) = synchronizer._processes.values()
    assert live.sync_status == "⟳ Syncing"

    start = time.time()
    live.stop()
    assert time.time() - start < 10
    assert process.poll() is not None
    assert not synchronizer._processes
    assert live.state.name == "STOPPED"


def test_process_service_stopped_while_starting(tmp_path):
    """A process service can be stopped before it is ready"""
    from experimaestro.scheduler.services import ProcessWebService, ServiceState

    class _NeverReady(ProcessWebService):
        id = "never-ready"

        def _build_command(self):
            return ["sleep", "60"]

        def _wait_for_ready(self):
            while self.process.poll() is None:
                time.sleep(0.05)
            raise RuntimeError("exited")

    service = _NeverReady(log_directory=tmp_path)
    urls = []
    starting = threading.Thread(target=lambda: urls.append(service.get_url()))
    starting.start()
    while service.state != ServiceState.STARTING or service.process is None:
        time.sleep(0.01)

    service.stop()
    starting.join(timeout=10)
    assert urls == [None]
    assert service.state == ServiceState.STOPPED
    assert service.error is None


# --- Reconnection


def kill_connection(provider: SSHStateProviderClient) -> None:
    """Kill the SSH process (and the remote server it runs): the connection
    drops"""
    process = psutil.Process(provider._process.pid)
    for child in process.children(recursive=True):
        child.kill()
    process.kill()


def wait_for(predicate, timeout: float = 30.0) -> None:
    deadline = time.time() + timeout
    while not predicate():
        assert time.time() < deadline, "timed out"
        time.sleep(0.05)


def record_connection_events(
    provider: SSHStateProviderClient,
) -> list[ConnectionStateEvent]:
    events = []

    def listener(event):
        if isinstance(event, ConnectionStateEvent):
            events.append(event)

    provider.add_listener(listener)
    return events


def test_reconnect(remote_workspace, fake_ssh):
    """The client reconnects when the connection drops: the watched
    experiments are sent again, and the cached answers dropped (events were
    missed) while keeping the cached objects"""
    provider = connect(
        remote_workspace,
        "-m",
        "experimaestro",
        reconnect=ReconnectSettings(max_retries=3, delay=0.1),
    )
    events = record_connection_events(provider)
    watches = []
    send_watch = provider._send_watch

    def record_watch(experiments):
        watches.append(experiments)
        send_watch(experiments)

    provider._send_watch = record_watch
    try:
        provider.watch("ui", {"greetings"})
        (experiment,) = provider.get_experiments()
        watches.clear()

        kill_connection(provider)
        wait_for(lambda: events and events[-1].state == "connected")

        assert [event.state for event in events] == ["reconnecting", "connected"]
        assert events[0].attempt == 1 and events[0].max_retries == 3
        assert provider.connection_state == ConnectionState.CONNECTED
        assert watches == [frozenset({"greetings"})]
        assert ("experiments", None) not in dict(provider._query_cache.entries())
        # Read again, into the same object
        (again,) = provider.get_experiments()
        assert again is experiment
    finally:
        provider.disconnect()
    assert provider.connection_state == ConnectionState.DISCONNECTED


def test_reconnect_gives_up(remote_workspace, fake_ssh):
    """At most max_retries attempts are made within the time window: the
    client is then disconnected"""
    provider = connect(
        remote_workspace,
        "-m",
        "experimaestro",
        reconnect=ReconnectSettings(max_retries=2, delay=0.1),
    )
    events = record_connection_events(provider)
    try:
        # The remote server cannot be started anymore
        provider.remote_xpm_path = "false"
        kill_connection(provider)
        wait_for(lambda: events and events[-1].state == "disconnected")

        assert [(event.state, event.attempt) for event in events] == [
            ("reconnecting", 1),
            ("reconnecting", 2),
            ("disconnected", 2),
        ]
        assert events[-1].error
        assert provider.connection_state == ConnectionState.DISCONNECTED
        with pytest.raises(ConnectionError, match="disconnected"):
            provider._call_sync(RPCMethod.GET_EXPERIMENTS, {})
    finally:
        provider.disconnect()
