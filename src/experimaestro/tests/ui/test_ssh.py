def test_old_remote(old_ssh_provider):
    """Methods an older remote does not handle are refused with a clear message"""
    assert old_ssh_provider.supports(RPCMethod.GET_EXPERIMENTS)
    assert not old_ssh_provider.supports(RPCMethod.GET_RUN_OBJECTS)
    experiments = old_ssh_provider.get_experiments()
    assert {xp.experiment_id for xp in experiments} == {"greetings"}
    with pytest.raises(RemoteMethodNotSupported, match="update experimaestro"):
        old_ssh_provider.get_run_objects("greetings", None)


def test_trace(remote_workspace, fake_ssh, caplog):
    """Requests are traced on both sides (the remote logs are shown locally)"""
    remote_output = []
    provider = connect(
        remote_workspace,
        "-m",
        "experimaestro",
        remote_log_levels="xpm.remote.trace=DEBUG",
        output_callback=remote_output.append,
    )
    try:
        with caplog.at_level(logging.DEBUG, logger="xpm.remote.trace"):
            provider.get_experiments()
    finally:
        provider.disconnect()
    assert any("get_experiments #" in line for line in remote_output)
    assert any(
        "get_experiments #" in r.message and "round trip" in r.message
        for r in caplog.records
    )


def test_job_info_reads_one_experiment(ssh_provider, remote_workspace, caplog):
    """The job information of an experiment is not read through the list of all
    experiments (which is large: it holds the job information of every run)"""
    with caplog.at_level(logging.DEBUG, logger="xpm.remote.trace"):
        current = ssh_provider.get_experiment_job_info("greetings", refresh=True)
        run_id = ssh_provider.get_current_run("greetings")
        by_run = ssh_provider.get_experiment_job_info("greetings", run_id, refresh=True)
    assert set(current) == set(by_run) == set(remote_workspace.jobs.values())
    methods = {r.message.split(" #")[0] for r in caplog.records}
    assert "get_experiments" not in methods
