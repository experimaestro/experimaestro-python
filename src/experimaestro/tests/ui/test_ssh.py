FAKE_SSH = """#!/bin/sh
# Fake ssh: skips the options and the host, runs the command locally
while [ $# -gt 0 ]; do
  case "$1" in
    -[bcDEeFIiJLlmOopQRSWw]) shift 2;;
    -*) shift;;
    *) break;;
  esac
done
shift
exec sh -c "$*"
"""


class Greet(Task):
    name: Param[str]

    def execute(self):
        print(f"hello {self.name}")  # noqa: T201 (the job log)


@dataclass
class RemoteWorkspace:
    path: Path
    #: Job identifiers by greeted name
    jobs: dict[str, str]


@pytest.fixture(scope="module")
def remote_workspace(tmp_path_factory) -> RemoteWorkspace:
    workdir = tmp_path_factory.mktemp("remote").resolve()
    with TemporaryExperiment("greetings", workdir=workdir):
        tasks = {
            name: Greet.C(name=name).tag("who", name).submit()
            for name in ("alice", "bob")
        }
    return RemoteWorkspace(
        workdir,
        {name: task.__xpm__.job.identifier for name, task in tasks.items()},
    )


#: A remote experimaestro predating get_run_objects (2.7.0): its server does
#: not list the methods it handles
OLD_SERVER = """
from experimaestro.__main__ import main
from experimaestro.scheduler.remote.server import SSHStateProviderServer

handlers = SSHStateProviderServer.__init__
sync_info = SSHStateProviderServer._handle_get_sync_info


def __init__(self, *args, **kwargs):
    handlers(self, *args, **kwargs)
    del self._handlers["get_run_objects"]


def _handle_get_sync_info(self, params):
    info = sync_info(self, params)
    del info["methods"], info["version"]
    return info


SSHStateProviderServer.__init__ = __init__
SSHStateProviderServer._handle_get_sync_info = _handle_get_sync_info
main()
"""


@pytest.fixture
def fake_ssh(tmp_path, monkeypatch):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    ssh = bin_dir / "ssh"
    ssh.write_text(FAKE_SSH)
    ssh.chmod(0o755)
    monkeypatch.setenv("PATH", str(bin_dir), prepend=os.pathsep)


def connect(
    workspace: RemoteWorkspace, *remote_xpm: str, **kwargs
) -> SSHStateProviderClient:
    kwargs.setdefault("output_callback", lambda _: None)
    provider = SSHStateProviderClient(
        "remote-host",
        str(workspace.path),
        remote_xpm_path=shlex.join([sys.executable, *remote_xpm]),
        **kwargs,
    )
    provider.connect()
    return provider


